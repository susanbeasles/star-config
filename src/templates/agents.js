import { guardCommand } from '../hook-boundary.js';
import { describeStacks } from '../detect.js';

/** @typedef {import('./governance.js').Ctx} Ctx */

/** @param {NonNullable<Ctx['stacks']['node']>} n */
function nodeNotes(n) {
  const notes = [
    n.lintProfile === 'biome'
      ? "- **JS/TS:** Biome lints + formats. Don't add ESLint or Prettier configs."
      : "- **JS/TS:** Prettier formats, ESLint enforces (sonarjs + typescript-eslint). Don't hand-format; don't disable rules inline without a justification comment.",
    `- **Package manager:** \`${n.pm}\` only. Commit the lockfile. Exact versions (\`save-exact\`).`,
    `- **Tests:** Vitest for unit/integration (\`*.test.ts\` next to the code).${n.web ? ' Playwright for E2E (`e2e/`).' : ''}`,
  ];
  if (n.typescript) {
    notes.push(
      '- **TypeScript:** pinned to 6.0.x because typescript-eslint and sonarjs do not support TS 7 yet.',
    );
  }
  if (n.cdk) {
    notes.push(
      '- **AWS CDK:** cdk-nag `AwsSolutionsChecks` + `HIPAASecurityChecks` run on every synth. Fix findings; suppress only with `NagSuppressions` + a written reason.',
    );
  }
  if (n.reactNative) {
    notes.push(
      "- **React Native:** Vitest covers logic/hooks; component tests need the RN preset. Mobile E2E is out of Playwright's scope (use Maestro/Detox).",
    );
  }
  return notes;
}

/** @type {Array<[keyof Ctx['stacks'], string]>} */
const OTHER_NOTES = [
  [
    'python',
    '- **Python:** use the project venv at `.venv` (`uv run …`). Ruff lints + formats; pytest for tests (`tests/test_*.py`). Add deps with `uv add`, never `pip install` into the venv.',
  ],
  [
    'rust',
    '- **Rust:** rustfmt + `cargo clippy -D warnings`; cargo-deny gates advisories and licenses. No `unwrap()` in non-test code.',
  ],
  ['swift', '- **Swift:** SwiftLint (strict) + swift-format. No force unwraps / `try!`.'],
  [
    'shell',
    '- **Shell:** `set -euo pipefail`; ShellCheck-clean; shfmt formatted; tests in bats (`*.bats`).',
  ],
  [
    'docker',
    '- **Docker:** hadolint-clean; non-root `USER`; pin base images by digest in production Dockerfiles.',
  ],
  [
    'terraform',
    '- **Terraform:** `terraform fmt` + tflint; Trivy and Checkov gate misconfigurations (encryption, public exposure, logging). Never commit `*.tfstate` or `.terraform/`.',
  ],
  [
    'cloudflare',
    '- **Cloudflare Workers:** secrets via `wrangler secret put`, never `vars`; `workers_dev = false` when routes exist (wrangler-nag enforces).',
  ],
];

/** @param {Ctx} ctx */
function stackNotes(ctx) {
  const notes = ctx.stacks.node ? nodeNotes(ctx.stacks.node) : [];
  for (const [key, note] of OTHER_NOTES) {
    if (ctx.stacks[key]) {
      notes.push(note);
    }
  }
  return notes.join('\n');
}

/** @param {Ctx} ctx */
export function agentsMd(ctx) {
  const stacks = describeStacks(ctx.stacks);
  return `# AGENTS.md

Instructions for AI coding agents (Claude Code, Codex, Copilot, Cursor…) and humans.
Generated by star-config v${ctx.version}; edit freely — \`star-config sync\` won't overwrite a modified file.

## Project

${ctx.repoName} — ${stacks.length ? stacks.join(' · ') : 'no stacks detected yet'}.

## Commands

| Task | Command |
|---|---|
| First-time setup (deps, venv, tools, hooks) | \`.star/run setup\` |
| Lint + format check | \`.star/run lint\` (\`--fix\` to write) |
| Format only | \`.star/run format\` |
| Tests | \`.star/run test\`${ctx.stacks.node?.web ? ' (`--e2e` for Playwright)' : ''} |
| Build | \`.star/run build\` |
| Security audit (secrets, deps, SAST, IaC) | \`.star/run audit\` |
| Everything CI runs | \`.star/run check\` |

Run \`.star/run check\` before declaring a task done. It must pass.

## Non-negotiables (HIPAA / SOC 2)

- **No PHI or PII anywhere outside approved data stores**: not in code, comments, test fixtures,
  logs, error messages, analytics events, commit messages, or PR text. Use synthetic data.
- **Never log request/response bodies, tokens, or identifiers that map to a patient.**
  \`console.log\`/\`print\` are lint errors for this reason; use the structured logger with redaction.
- **No secrets in the repo.** Read them from the environment / secrets manager. Gitleaks blocks commits.
- **Minimum necessary:** query and return only the fields a feature needs.
- **Don't weaken controls** (auth checks, audit logging, encryption, lint/security rules, CI gates)
  to make something pass. If a control blocks you, stop and explain.
- **Don't read** \`.env*\`, key files, or anything under \`secrets/\`.

## Conventions

${stackNotes(ctx)}
- **Commits:** small and focused, imperative subject (\`fix: …\`, \`feat: …\`). Hooks run automatically; never \`--no-verify\`.
- **Dependencies:** prefer the standard library and existing deps. New deps need a reason in the PR.

## Definition of done

1. \`.star/run check\` passes.
2. New behavior has tests; bug fixes have a regression test.
3. The PR template's security checklist is truthfully filled in.
`;
}

export function claudeMd() {
  return `# CLAUDE.md

@AGENTS.md

## Claude Code specifics

- After every edit, a PostToolUse hook calls the administrator-installed agent-guard runner, which
  formats and lints the changed file in an isolated runtime. If it reports errors, fix them before moving on.
- Use plan mode for changes touching auth, data access, infra, or more than ~5 files.
- Permissions in \`.claude/settings.json\` deny reading secrets; don't work around them.
`;
}

